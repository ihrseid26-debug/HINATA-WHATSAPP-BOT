function buildGuide() {
  const lines = [
    HEADER,
    '',
    '*🌸 مَـرْكَـزُ فَـعَـالِـيَـات HINATA 🌸*',
    '*『 ENTERTAINMENT • EVENTS • QUIZZES 』*',
    '',
    '❄️ دليل الأوامر الجديد والقديم في رسالة واحدة.',
    '❄️ الصور: استخدم .صورة ثم اكتب وصف الصورة المطلوبة.',
    ''
  ];

  for (const section of sections) {
    lines.push(`*╭━━〔 ${section.title} 〕━━╮*`, '');
    for (const [name, description] of section.items) {
      lines.push(`*•┆❄️〖 .${name} 〗*`, `⟞ ${description}`, '');
    }
  }

  lines.push('*╭━━〔 🎉 أوامر الفعاليات القديمة 〕━━╮*', '');
  for (const [name, description] of legacy) {
    lines.push(`*•┆❄️〖 .${name} 〗*`, `⟞ ${description}`, '');
  }

  lines.push(
    '*╭━━〔 🖼️ الصور 〕━━╮*',
    '',
    '*•┆❄️〖 .صورة 〗*',
    '⟞ ابحث عن صورة بكتابة وصفها بعد الأمر.',
    '',
    FOOTER
  );

  return lines.join('\n');
}

export function registerHinataEventsCenter(commands) {
  let added = 0;
  let skipped = 0;

  for (const section of sections) {
    for (const [name, description, content] of section.items) {
      if (commands.has(name)) {
        skipped++;
        console.warn(`[HINATA EVENTS] Existing command preserved: ${name}`);
        continue;
      }

      commands.set(name, {
        description,
        reaction: '❄️',
        handler: async ctx => {
          await ctx.reply(
            `${HEADER}\n\n` +
            `*🌸 HINATA • ${section.title}*\n\n` +
            `*•┆❄️〖 .${name} 〗*\n` +
            `${content}\n\n` +
            `${FOOTER}`
          );
        }
      });

      added++;
    }
  }

  if (commands.has('قسم_الفعاليات')) {
    throw new Error(
      '[HINATA EVENTS] القسم القديم ما زال مسجلاً. أزل واجهته القديمة أولاً.'
    );
  }

  commands.set('قسم_الفعاليات', {
    description: 'دليل فعاليات HINATA الشامل',
    reaction: '🎉',
    handler: async ctx => {
      let imageBuffer = null;

      try {
        imageBuffer = await getSubbotSectionImage(ctx, 'الفعاليات');
      } catch (error) {
        console.error('[HINATA EVENTS IMAGE ERROR]', error);
      }

      await sendHinataNativeButtons(ctx.sock, ctx.jid, {
        ...(imageBuffer ? { imageBuffer } : {}),
        text: buildGuide(),
        footer: '🌸 HINATA • EVENTS CENTER',
        buttons: [{
          type: 'single_select',
          title: '❄️ خيارات القائمة',
          sections: [{
            title: '🌸 التنقل',
            rows: [{
              title: '↩️ رجوع إلى قائمة الأوامر',
              description: 'العودة إلى القائمة الرئيسية',
              id: '.اوامر'
            }]
          }]
        }]
      });
    }
  });

  console.log(
    `[HINATA EVENTS] Registered ${added} new commands; preserved ${skipped} collisions.`
  );
}
